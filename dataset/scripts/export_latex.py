def tab_composition(S, dest):
    L = [r"\begin{table*}[t]", r"\caption{Forgery categories, their intended",
         r"detectability, and the realised image counts per document type.",
         r"$\dsCellControls$ control images per document type comprise two",
         r"unmodified renders of every record at $\dsNq$ quality tiers. C2, C3",
         r"and C4 are produced by re-rendering from a modified record, so they",
         r"carry no pixel-level trace; C1 is the only category in which pixels",
         r"are edited after rendering, and it leaves every printed value valid.}",
         r"\label{tab:forgery}", r"\centering", r"\footnotesize",
         r"\begin{tabular}{@{}l p{7.2cm} l p{2.7cm} r r@{}}", r"\toprule",
         r"Cat. & Construction & Visual branch & Rule branch & Aadhaar & PAN \\",
         r"\midrule"]
    for c in CATS:
        d, v, r = INTENT[c]
        L.append(f"{c} & {d} & {v} & {r} & "
                 f"{S['composition_by_cell'][f'aadhaar/{c}']} & "
                 f"{S['composition_by_cell'][f'pan/{c}']} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    _w(dest, "tab_composition.tex", "\n".join(L) + "\n")


def tab_ocr(S, dest):
    L = [r"\begin{table}[t]",
         r"\caption{Per-field OCR extraction quality by capture quality tier:",
         r"exact-match rate with a 95\% Wilson interval, and mean character",
         r"error rate. Raw Tesseract output, with only the parsing step of",
         r"Section~\ref{subsec:ocr} applied.}", r"\label{tab:ocr}", r"\centering",
         r"\footnotesize", r"\begin{tabular}{@{}llrrr@{}}", r"\toprule",
         r"Field & Tier & $n$ & Exact match \% [95\% CI] & CER \% \\",
         r"\midrule"]
    order = [("aadhaar", "aadhaar_number", "A: number"),
             ("aadhaar", "name", "A: name"),
             ("aadhaar", "dob", "A: DOB"),
             ("pan", "pan_number", "P: number"),
             ("pan", "name", "P: name"),
             ("pan", "father_name", "P: father"),
             ("pan", "dob", "P: DOB")]
    for dt, fld, label in order:
        for i, t in enumerate(TIERS):
            v = S["ocr"].get(f"{dt}/{fld}/{t}")
            if not v:
                continue
            nm = label if i == 0 else ""
            L.append(f"{nm} & {t} & {v['n']} & {v['exact_match_pct']:.1f} "
                     f"[{v['ci95'][0]:.1f}, {v['ci95'][1]:.1f}] & "
                     f"{v['mean_cer_pct']:.2f} \\\\")
        if (dt, fld) != order[-1][:2]:
            L.append(r"\addlinespace[1.5pt]")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    _w(dest, "tab_ocr.tex", "\n".join(L) + "\n")


def tab_rule(S, dest):
    L = [r"\begin{table}[t]",
         r"\caption{Rule-branch flag rate by forgery category (\% of images on",
         r"which an applicable rule evaluated \textsc{false}), on ground-truth",
         r"text and on OCR-extracted text, with 95\% Wilson intervals. On C0 a",
         r"flag is a false positive. On C4 both branches are expected to miss by",
         r"construction, so a flag there is an OCR-induced false alarm and not",
         r"detection of the fabrication.}", r"\label{tab:rulerate}",
         r"\centering", r"\footnotesize", r"\begin{tabular}{@{}llll@{}}",
         r"\toprule",
         r"Document & Cat. & Ground-truth text & OCR text \\", r"\midrule"]
    for dt in ("aadhaar", "pan"):
        for i, c in enumerate(CATS):
            g = S["rule_flag_rate_by_category"][f"{dt}/{c}/gt"]["pct_ci"]
            o = S["rule_flag_rate_by_category"][f"{dt}/{c}/ocr"]["pct_ci"]
            nm = ("Aadhaar" if dt == "aadhaar" else "PAN") if i == 0 else ""
            L.append(f"{nm} & {c} & {g} & {o} \\\\")
        if dt == "aadhaar":
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    _w(dest, "tab_rule_rate.tex", "\n".join(L) + "\n")


def tab_fp(S, dest):
    L = [r"\begin{table}[t]",
         r"\caption{Rule-branch false-positive rate on \emph{genuine} documents",
         r"(category C0) as a function of capture quality, evaluated on",
         r"OCR-extracted text. On ground-truth text the rate is zero by",
         r"construction, so every entry here is attributable to OCR extraction",
         r"error. This is the measurement RQ6 requires.}",
         r"\label{tab:fpr}", r"\centering", r"\footnotesize",
         r"\begin{tabular}{@{}llrrl@{}}", r"\toprule",
         r"Document & Tier & $n$ & FP & FP rate \% [95\% CI] \\", r"\midrule"]
    for dt in ("aadhaar", "pan"):
        for i, t in enumerate(TIERS + ["ALL"]):
            v = S["rule_false_positive_on_genuine_ocr"][f"{dt}/{t}"]
            nm = ("Aadhaar" if dt == "aadhaar" else "PAN") if i == 0 else ""
            lab = "all" if t == "ALL" else t
            L.append(f"{nm} & {lab} & {v['n']} & {v['fp']} & {v['pct_ci']} \\\\")
        if dt == "aadhaar":
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    _w(dest, "tab_fpr.tex", "\n".join(L) + "\n")


def tab_perm(S, dest):
    ps = S["pan_semantic_permissive_vs_strict_on_genuine"]
    L = [r"\begin{table}[t]",
         r"\caption{PAN cross-field rule on \emph{genuine} documents:",
         r"permissive rule (2) against the strict variant, by naming stratum and",
         r"by the source of the fifth character. A failure here is a false",
         r"positive on a genuine document. The strict variant is reported as a",
         r"sensitivity analysis, not as the study's rule.}",
         r"\label{tab:permstrict}", r"\centering", r"\scriptsize",
         r"\setlength{\tabcolsep}{3.5pt}",
         r"\begin{tabular}{@{}llrll@{}}", r"\toprule",
         r"Subset & Text & $n$ & Permissive FAIL \% & Strict FAIL \% \\",
         r"\midrule"]
    rows = ["ALL", "surname_last", "initial_first", "mononymic",
            "p5src:leading_initial", "p5src:given_name"]
    for k in rows:
        for src in ("gt", "ocr"):
            v = ps.get(f"{k}/{src}")
            if not v:
                continue
            short = {"ALL": "all genuine PAN",
                     "surname_last": "surname-last",
                     "initial_first": "initial-first",
                     "mononymic": "mononymic",
                     "p5src:leading_initial": "$p_5$ from initial",
                     "p5src:given_name": "$p_5$ from given name"}.get(k, esc(k))
            lab = short if src == "gt" else ""
            L.append(f"{lab} & {src} & {v['n']} & "
                     f"{v['permissive_fail_pct_ci']} & {v['strict_fail_pct_ci']} \\\\")
        L.append(r"\addlinespace[1.5pt]")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    _w(dest, "tab_perm_strict.tex", "\n".join(L) + "\n")


def tab_leakage(S, dest):
    lk = S["leakage"]
    nd = lk["near_duplicate"]
    ident = lk["identity"]["pairwise_person_id_intersections"]
    idf = lk["identifier"]["pairwise_identifier_intersections"]
    L = [r"\begin{table}[t]",
         r"\caption{Leakage audit performed on the released splits. Each check is",
         r"run on the corpus and its outcome reported, rather than asserted. The",
         r"first four checks are exact and all pass. The fifth, near-duplicate",
         r"detection by perceptual hashing, is reported as a \emph{diagnostic}",
         r"rather than a gate: on a corpus in which every document shares one",
         r"of six layout templates, the same-document and different-person",
         r"distance distributions overlap, so no threshold can separate a",
         r"leaked duplicate from two unrelated documents. See",
         r"Section~\ref{subsec:leakage} and Fig.~\ref{fig:phash}.}",
         r"\label{tab:leakage}", r"\centering", r"\scriptsize",
         r"\setlength{\tabcolsep}{3.5pt}",
         r"\begin{tabular}{@{}p{1.15cm}p{3.0cm}ll@{}}", r"\toprule",
         r"Leakage mode & Check & Required & Observed \\", r"\midrule",
         r"Identity & person-id intersection across splits & empty & "
         f"{max(ident.values()) if ident else 0} " + r"\\",
         r"Identifier & Aadhaar/PAN string intersection & empty & "
         f"{max(idf.values()) if idf else 0} " + r"\\",
         r"Template & every layout variant in every split & all & "
         f"{min(lk['template']['variants_per_split'].values())}/"
         f"{lk['template']['total_variants']} " + r"\\",
         r"Near-duplicate & \dsPhashBits-bit perceptual-hash distance & "
         r"(diagnostic) & see Sec.~\ref{subsec:leakage} \\",
         r"Augment\-ation & degradation draws of one document & one split & "
         f"{lk['augmentation']['documents_spanning_splits']} span splits " + r"\\",
         r"Printed values & identical field-value set in two splits & none & "
         f"{lk['printed_values']['sets_spanning_splits']} of "
         f"{lk['printed_values']['distinct_printed_value_sets']} " + r"\\",
         r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    _w(dest, "tab_leakage.tex", "\n".join(L) + "\n")


def _w(dest, name, text):
    os.makedirs(dest, exist_ok=True)
    with open(os.path.join(dest, name), "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", os.path.join(dest, name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/v1")
    ap.add_argument("--dest", default="paper/generated")
    a = ap.parse_args()
    S = json.load(open(os.path.join(a.out, "stats", "dataset_stats.json")))
    macros(S, a.dest, a.out)
    tab_composition(S, a.dest)
    tab_ocr(S, a.dest)
    tab_rule(S, a.dest)
    tab_fp(S, a.dest)
    tab_perm(S, a.dest)
    tab_leakage(S, a.dest)


if __name__ == "__main__":
    main()
