# -*- coding: utf-8 -*-
"""Emit LaTeX macros and tables from the built dataset.

    python scripts/export_latex.py --out data/v1 --dest paper/generated

Every number that appears in Section IV of the paper comes from here, so a
number in the text can never drift away from the corpus it describes.  Rebuild
the dataset, re-run this, recompile: the paper updates itself.
"""
from __future__ import annotations

import argparse
import json
import os

CATS = ["C0", "C1", "C2", "C3", "C4"]
TIERS = ["clean", "mild", "severe"]

INTENT = {
    "C0": ("Unmodified render", "pass", "pass"),
    "C1": ("Post-render pixel edit; every printed value remains valid",
           "detect", "pass"),
    "C2": ("Re-render with a structurally invalid identifier: Aadhaar checksum "
           "broken, or PAN format or category character broken", "miss",
           "detect"),
    "C3": ("Re-render with a semantically inconsistent field pair: PAN fifth "
           "character against the name, Aadhaar Latin against Devanagari name",
           "miss", "detect (PAN only)"),
    "C4": ("Re-render with a fabricated identifier that satisfies every rule",
           "miss", "miss"),
}


def esc(s):
    return str(s).replace("_", r"\_").replace("%", r"\%")


def probe_macros(out_dir, L):
    import os
    q = os.path.join(out_dir, "stats", "renderer_probe.json")
    if not os.path.exists(q):
        return
    P = json.load(open(q))
    a = P["exact_difference_audit"]
    L.append(rf"\newcommand{{\dsProbeRecords}}{{{a['n_records_audited']}}}")
    L.append(rf"\newcommand{{\dsProbeCells}}{{{len(a['per_cell'])}}}")
    L.append(rf"\newcommand{{\dsProbeComparisons}}{{"
             rf"{sum(v['n'] for v in a['per_cell'].values())}}}")
    L.append(rf"\newcommand{{\dsProbeOutside}}{{"
             rf"{a['total_pixels_changed_outside_expected_region']}}}")
    for t, nm in (("critical", "Critical"), ("control", "Control"),
                  ("critical_clean", "CriticalClean"),
                  ("control_clean", "ControlClean")):
        v = P.get(f"learned_probe_{t}")
        if v:
            import math
            b, n = v["balanced_accuracy"], v["n_test"]
            hw = 1.959963985 * math.sqrt(0.25 / max(1, n))
            L.append(rf"\newcommand{{\dsProbe{nm}}}{{{b:.3f}}}")
            L.append(rf"\newcommand{{\dsProbe{nm}AUC}}{{{v['auroc']:.3f}}}")
            L.append(rf"\newcommand{{\dsProbe{nm}N}}{{{n}}}")
            L.append(rf"\newcommand{{\dsProbe{nm}CI}}{{$[{max(0.0, b-hw):.3f},\,"
                     rf"{min(1.0, b+hw):.3f}]$}}")


