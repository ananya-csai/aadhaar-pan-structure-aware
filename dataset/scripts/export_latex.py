    ca = S["coincidence"]
    a_hi = ca["aadhaar"]["1420000000.0"]
    p_hi = ca["pan"]["800000000.0"]
    L = [
        "% Auto-generated by scripts/export_latex.py -- do not edit by hand.",
        rf"\newcommand{{\dsPersons}}{{{T['persons']}}}",
        rf"\newcommand{{\dsDocuments}}{{{T['documents']}}}",
        rf"\newcommand{{\dsImages}}{{{T['images']}}}",
        rf"\newcommand{{\dsGenuine}}{{{T['images_genuine']}}}",
        rf"\newcommand{{\dsForged}}{{{T['images_forged']}}}",
        rf"\newcommand{{\dsGiB}}{{{S['storage']['total_gib']:.2f}}}",
        rf"\newcommand{{\dsNq}}{{{len(TIERS)}}}",
        rf"\newcommand{{\dsTrainImg}}{{{S['split_sizes'].get('train',0)}}}",
        rf"\newcommand{{\dsValImg}}{{{S['split_sizes'].get('val',0)}}}",
        rf"\newcommand{{\dsTestImg}}{{{S['split_sizes'].get('test',0)}}}",
        rf"\newcommand{{\dsTrainPer}}{{{S['split_persons'].get('train',0)}}}",
        rf"\newcommand{{\dsValPer}}{{{S['split_persons'].get('val',0)}}}",
        rf"\newcommand{{\dsTestPer}}{{{S['split_persons'].get('test',0)}}}",
        rf"\newcommand{{\dsCellImages}}{{{S['composition_by_cell']['aadhaar/C1']}}}",
        rf"\newcommand{{\dsCellControls}}{{{S['composition_by_cell']['aadhaar/C0']}}}",
        rf"\newcommand{{\dsPhashBits}}{{{nd['hash_bits']}}}",
        rf"\newcommand{{\dsPhashDistinctSixtyFour}}{{{nd['distinct_hashes_64bit']}}}",
        rf"\newcommand{{\dsPhashDistinct}}{{{nd['distinct_hashes_used']}}}",
        rf"\newcommand{{\dsPhashAUC}}{{{nd['separability_auc_within_vs_crossperson']:.3f}}}",
        rf"\newcommand{{\dsPhashOverlap}}{{{100*nd['cross_person_pairs_closer_than_median_within_document']:.1f}}}",
        rf"\newcommand{{\dsPhashWithinMed}}{{{nd['within_document']['median']:.0f}}}",
        rf"\newcommand{{\dsPhashCrossPersonMed}}{{{nd['cross_person_same_split']['median']:.0f}}}",
        rf"\newcommand{{\dsPhashCrossPersonMin}}{{{nd['cross_person_same_split']['min']}}}",
        rf"\newcommand{{\dsAadhaarSpace}}{{8\times10^{{10}}}}",
        rf"\newcommand{{\dsPanSpace}}{{4.6\times10^{{10}}}}",
        rf"\newcommand{{\dsAadhaarStrings}}{{{ca['n_distinct_aadhaar_strings']}}}",
        rf"\newcommand{{\dsPanStrings}}{{{ca['n_distinct_pan_strings']}}}",
        rf"\newcommand{{\dsAadhaarCoinPct}}{{{100*a_hi['p_single']:.1f}}}",
        rf"\newcommand{{\dsAadhaarCoinExp}}{{{a_hi['expected_coincidences']:.0f}}}",
        rf"\newcommand{{\dsPanCoinPct}}{{{100*p_hi['p_single']:.1f}}}",
        rf"\newcommand{{\dsPanCoinExp}}{{{p_hi['expected_coincidences']:.0f}}}",
    ]
    ps = S["pan_semantic_permissive_vs_strict_on_genuine"]
    for key, nm in (("ALL", "All"), ("initial_first", "InitialFirst"),
                    ("p5src:leading_initial", "LeadingInitial")):
        v = ps.get(f"{key}/gt")
        if v:
            L.append(rf"\newcommand{{\dsStrict{nm}}}{{{v['strict_fail_pct_ci'].split(' ')[0]}}}")
    import math
    for n, nm in ((900, "Cell"), (300, "Person")):
        hw = 100 * 1.959963985 * math.sqrt(0.9 * 0.1 / n)
        L.append(rf"\newcommand{{\dsCI{nm}}}{{{hw:.1f}}}")
    for dt in ("aadhaar", "pan"):
        for t in TIERS + ["ALL"]:
            v = S["rule_false_positive_on_genuine_ocr"][f"{dt}/{t}"]
            pct = v["pct_ci"].split(" ")[0]
            L.append(rf"\newcommand{{\dsFP{dt.capitalize()}{t.capitalize()}}}{{{pct}}}")
    for key in ("aadhaar/aadhaar_number", "pan/pan_number", "aadhaar/name", "pan/name"):
        for t in TIERS:
            v = S["ocr"].get(f"{key}/{t}")
            if v:
                nm = "".join(w.capitalize() for w in key.replace("/", "_").split("_"))
                L.append(rf"\newcommand{{\dsOcr{nm}{t.capitalize()}}}{{{v['exact_match_pct']:.1f}}}")
    if out_dir:
        probe_macros(out_dir, L)
